def _target(fullname: str) -> str | None:
    for old, new in ALIASES.items():
        if fullname == old or fullname.startswith(old + "."):
            return new + fullname[len(old) :]
    return None


class _Alias(importlib.abc.Loader):
    def __init__(self, real: str) -> None:
        self.real = real

    def create_module(self, spec: importlib.machinery.ModuleSpec) -> ModuleType:
        return importlib.import_module(self.real)

    def exec_module(self, module: ModuleType) -> None:  # the real module is already executed
        return None


class _Finder(importlib.abc.MetaPathFinder):
    def find_spec(self, fullname: str, path: Any = None, target: Any = None) -> importlib.machinery.ModuleSpec | None:
        real = _target(fullname)
        if real is None:
            return None
        if importlib.util.find_spec(real) is None:
            return None
        return importlib.util.spec_from_loader(fullname, _Alias(real))


def install() -> None:
    if not any(isinstance(f, _Finder) for f in sys.meta_path):
        sys.meta_path.insert(0, _Finder())  # before PathFinder, or the old name loads a second copy
