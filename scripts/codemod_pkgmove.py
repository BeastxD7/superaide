#!/usr/bin/env python3
"""Move backend packages into group folders (docs/decisions/0015-project-layout.md, phases 3 to 5).

    codemod_pkgmove.py --phase 4              # features/*: the 13 leaf packages
    codemod_pkgmove.py --move mirror=features/mirror --move voice=features/voice   # any mapping
    codemod_pkgmove.py --phase 4 --dry-run

For every `old=new` (package folders under backend/src/superaide, `new` a path below it):
  1. `git mv` the folder (history follows) and make sure the group folder is a package;
  2. rewrite `superaide.old` -> `superaide.new` (dotted, in code, strings, docs, patch targets) and the path forms
     `backend/src/superaide/old`, `src/superaide/old`, `superaide/old` in every tracked text file (module map,
     CODEOWNERS, surface.toml and surface.lock.json, workflows, docs);
  3. deepen `Path(__file__)...parents[n]` in the moved files by the extra folder levels;
  4. record the move in ci/layout-moves.json (`prefixes`, `modules`, `aliases`) and regenerate
     backend/src/superaide/_compat.py from `aliases`: a meta-path finder that keeps `import superaide.old.x`
     working, as the same module object, for one release (ADR 0015 "Compatibility shim").
It is idempotent (a package already at its new place is skipped; a second run changes nothing) and never edits
a revision under backend/alembic (they import `superaide.platform.db.rls`, which phase 3 keeps as a permanent shim).
"""

